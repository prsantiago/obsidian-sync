import { type App, Notice, PluginSettingTab, Setting, type Plugin } from "obsidian";
import type { SyncPluginCore } from "./sync-plugin-core";

export class GoogleDriveSyncSettingTab extends PluginSettingTab {
  private readonly core: SyncPluginCore;

  constructor(app: App, plugin: Plugin, core: SyncPluginCore) {
    super(app, plugin);
    this.core = core;
  }

  display(): void {
    const { containerEl } = this;
    containerEl.empty();

    containerEl.createEl("h2", { text: "Google Drive Sync" });

    const info = this.core.getConnectionInfo();

    // Read-only connection status card
    const card = containerEl.createDiv({ cls: "gdrive-sync-status-card" });
    this.addStatusRow(card, "Status", info.connected ? "Connected" : "Disconnected");
    if (info.connected) {
      this.addStatusRow(card, "Linked Folder", info.rootFolderName ?? "—");
      this.addStatusRow(card, "Folder ID", info.rootFolderId ?? "—");
      this.addStatusRow(card, "OAuth Client ID", info.maskedClientId ?? "—");
    }

    // Configuration bundle import / re-import
    containerEl.createEl("h3", {
      text: info.connected ? "Re-import Configuration Bundle" : "Connect to Google Drive",
    });

    let bundleInput = "";
    const errorEl = containerEl.createDiv({ cls: "gdrive-sync-validation-error" });
    errorEl.style.display = "none";

    new Setting(containerEl)
      .setName("Configuration Bundle")
      .setDesc(
        "Paste the JSON or base64 configuration bundle generated by the Mac setup helper.",
      )
      .addTextArea((text) => {
        text.inputEl.addClass("gdrive-sync-bundle-input");
        text.setPlaceholder('{"clientId": "...", "rootFolderId": "..."}');
        text.onChange((value) => {
          bundleInput = value;
          errorEl.style.display = "none";
          errorEl.setText("");
        });
      });

    // Move error element right after the setting
    containerEl.appendChild(errorEl);

    new Setting(containerEl).addButton((btn) => {
      btn
        .setButtonText(info.connected ? "Re-import & Sync" : "Connect & Initial Sync")
        .setCta()
        .onClick(async () => {
          errorEl.style.display = "none";
          errorEl.setText("");
          btn.setDisabled(true);
          btn.setButtonText("Syncing...");
          try {
            await this.core.importConfigBundle(bundleInput);
            new Notice("Google Drive connected and initial sync complete.");
            this.display();
          } catch (err) {
            const msg = err instanceof Error ? err.message : String(err);
            errorEl.setText(msg);
            errorEl.style.display = "block";
          } finally {
            btn.setDisabled(false);
          }
        });
    });

    if (info.connected) {
      new Setting(containerEl)
        .setName("Disconnect Google Drive")
        .setDesc(
          "Clears stored OAuth credentials and sync index from this device. Local vault files are kept.",
        )
        .addButton((btn) => {
          btn
            .setButtonText("Disconnect")
            .setWarning()
            .onClick(async () => {
              await this.core.disconnect();
              new Notice("Disconnected from Google Drive.");
              this.display();
            });
        });
    }

    // Bounded Sync Error Log
    containerEl.createEl("h3", { text: "Sync Error Log" });
    const errorLog = this.core.getErrorLog();
    if (errorLog.length === 0) {
      containerEl.createEl("p", {
        cls: "setting-item-description",
        text: "No sync errors recorded.",
      });
    } else {
      new Setting(containerEl)
        .setName("Recent sync errors")
        .setDesc(`Showing ${errorLog.length} recorded error(s) (max 50).`)
        .addButton((btn) => {
          btn.setButtonText("Clear log").onClick(async () => {
            await this.core.clearErrorLog();
            this.display();
          });
        });

      const listEl = containerEl.createDiv({ cls: "gdrive-sync-error-log" });
      for (const entry of [...errorLog].reverse()) {
        const itemEl = listEl.createDiv({ cls: "gdrive-sync-error-log-entry" });
        itemEl.createSpan({
          cls: "gdrive-sync-error-log-time",
          text: `${new Date(entry.timestamp).toISOString()} — `,
        });
        itemEl.createSpan({
          cls: "gdrive-sync-error-log-msg",
          text: entry.message,
        });
      }
    }
  }

  private addStatusRow(parent: HTMLElement, label: string, value: string): void {
    const row = parent.createDiv({ cls: "gdrive-sync-status-row" });
    row.createSpan({ cls: "gdrive-sync-status-label", text: label });
    row.createSpan({ cls: "gdrive-sync-status-value", text: value });
  }
}
